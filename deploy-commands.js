require('dotenv').config();
const { REST, Routes, SlashCommandBuilder, PermissionFlagsBits } = require('discord.js');

if (!process.env.DISCORD_TOKEN || !process.env.DISCORD_CLIENT_ID) {
    throw new Error('DISCORD_TOKEN and DISCORD_CLIENT_ID must be set in the private environment.');
}

const commands = [
    new SlashCommandBuilder()
        .setName('ping')
        .setDescription('Check whether the Robblestone bot is online.'),
    new SlashCommandBuilder()
        .setName('testlogs')
        .setDescription('Send test punishment logs to the configured channels.')
        .setDefaultMemberPermissions(PermissionFlagsBits.ManageGuild),
    new SlashCommandBuilder()
        .setName('link')
        .setDescription('Link your Minecraft account to Discord.')
        .addStringOption(option => option
            .setName('code')
            .setDescription('Enter the 6-digit code generated by /link in Minecraft.')
            .setRequired(true)
            .setMinLength(6)
            .setMaxLength(6)),
    new SlashCommandBuilder()
        .setName('unlink')
        .setDescription('Unlink your Minecraft account and remove managed rank roles.')
].map(command => command.toJSON());

const rest = new REST({ version: '10' }).setToken(process.env.DISCORD_TOKEN);
rest.put(Routes.applicationCommands(process.env.DISCORD_CLIENT_ID), { body: commands })
    .then(() => console.log('Registered /ping, /testlogs, /link and /unlink.'))
    .catch(error => {
        console.error('Failed to register slash commands:', error);
        process.exitCode = 1;
    });
